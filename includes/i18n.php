function t(string $key, string $lang = null): string {
    global $I18N;
    if ($lang === null) {
        $lang = $_GET['lang'] ?? $_COOKIE['ui_lang'] ?? 'id';
    }
    return $I18N[$lang][$key] ?? $I18N['en'][$key] ?? $key;
}

function current_lang(): string {
    return $_GET['lang'] ?? $_COOKIE['ui_lang'] ?? 'id';
}

function lang_dir(): string {
    global $UI_LANGUAGES;
    $lang = current_lang();
    return $UI_LANGUAGES[$lang]['dir'] ?? 'ltr';
}
